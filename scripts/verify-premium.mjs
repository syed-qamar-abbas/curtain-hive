import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.addInitScript(() => sessionStorage.setItem('ch-intro', 'premium-v3'));
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const base = 'http://127.0.0.1:5173';
await page.goto(base + '/consultation/?service=motorized-blinds&room=Office&need=Convenience&style=Minimal');
await expect(page.getByLabel('What can we help with?')).toHaveValue('Motorized Blinds');
await expect(page.locator('.carried-preferences')).toContainText('Office · Convenience · Minimal');
await page.getByRole('button', { name: 'Prepare my consultation request', exact: true }).click();
await expect(page.locator('.confirmation')).toHaveCount(0);
await page.getByLabel('Your name', { exact: true }).fill('Local Preview');
await page.getByLabel('Phone / WhatsApp', { exact: true }).fill('03001234567');
await page.getByLabel('City / neighbourhood', { exact: true }).fill('Gulrez, Rawalpindi');
await page.getByRole('button', { name: 'Prepare my consultation request', exact: true }).click();
await expect(page.locator('.confirmation')).toContainText('no booking has been submitted');
const href = await page.getByRole('link', { name: 'Review & send on WhatsApp' }).getAttribute('href');
assert.equal(new URL(href).pathname, '/923015374238');
for (const value of ['Local Preview', 'Motorized Blinds', 'Gulrez, Rawalpindi', 'Office', 'Convenience', 'Minimal']) assert(decodeURIComponent(href).includes(value));
await page.getByRole('button', { name: 'Edit my details' }).click();
await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('Local Preview');
await page.getByRole('button', { name: 'Use guided planner', exact: true }).click();
await expect(page.getByRole('button', { name: 'Motorized Blinds', exact: true })).toHaveAttribute('aria-pressed', 'true');
await page.getByRole('button', { name: 'Use the short enquiry form' }).click();
await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('Local Preview');
const widths = [360, 390, 768, 1440, 1920];
for (const width of widths) {
  await page.setViewportSize({ width, height: 900 });
  await page.goto(base);
  await page.evaluate(() => document.fonts.ready);
  assert((await page.locator('h1').evaluate(n => getComputedStyle(n).fontFamily)).includes('Manrope'));
  const action = page.locator('.room-hero-copy .button');
  await expect(action).toBeVisible();
  const box = await action.boundingBox();
  assert(box.y + box.height <= 900, 'Primary action above fold at ' + width);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Overflow ' + width);
  const contrast = await action.evaluate(n => {
    const lum = c => { const channels = c.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => { v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }); return channels[0] * .2126 + channels[1] * .7152 + channels[2] * .0722; };
    const s = getComputedStyle(n), a = lum(s.color), b = lum(s.backgroundColor);
    return (Math.max(a, b) + .05) / (Math.min(a, b) + .05);
  });
  assert(contrast >= 4.5, 'CTA contrast ' + contrast);
}
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto(base);
assert.equal(await page.locator('.intro-curtain').count(), 0);
assert.equal(await page.evaluate(() => document.getAnimations().length), 0);
await page.locator('.light-preview summary').click();
const slider = page.getByRole('slider', { name: 'Compare softened light with original daylight' });
await slider.focus();
await page.keyboard.press('ArrowRight');
await expect(slider).toHaveValue('51');
await expect(page.locator('.light-study')).toContainText('not a before-and-after installation');
assert.deepEqual(errors, []);
mkdirSync('research/redesign-qa', { recursive: true });
writeFileSync('research/redesign-qa/flow-results.json', JSON.stringify({ passed: true, widths, errors, checks: ['Short enquiry validation', 'Studio preference handoff', 'Correct WhatsApp recipient and payload', 'No false booking confirmation', 'Edit retains data', 'Detailed planner remains available', 'Primary action visible in first viewport', 'Single Manrope heading family', 'No overflow', 'Burgundy button contrast AA', 'Reduced motion', 'Preserved keyboard light comparison with honest disclosure'] }, null, 2));
console.log('PASS: short enquiry, preserved planner, preference handoff, contact payload, responsive first-fold actions and reduced motion.');
await browser.close();

import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.addInitScript(() => sessionStorage.setItem('ch-intro', 'wordmark-v4'));
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const base = 'http://127.0.0.1:5173';
mkdirSync('research/navbar-fixes', { recursive: true });
await page.goto(base + '/portfolio/');
const services = page.locator('.desktop-nav').getByRole('button', { name: 'Services', exact: true });
const shop = page.locator('.desktop-nav').getByRole('button', { name: 'Shop', exact: true });
await services.hover(); await services.click();
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.mouse.click(1400, 800);
await expect(services).toHaveAttribute('aria-expanded', 'false');
await services.hover();
await shop.hover();
await expect(shop).toHaveAttribute('aria-expanded', 'true');
await expect(services).toHaveAttribute('aria-expanded', 'false');
await page.waitForTimeout(300);
await expect(shop).toHaveAttribute('aria-expanded', 'true');
await page.mouse.move(5, 5);
await expect(shop).toHaveAttribute('aria-expanded', 'false');
await services.hover();
const trigger = await services.boundingBox();
await page.mouse.move(trigger.x + 25, trigger.y + trigger.height + 8);
await page.waitForTimeout(350);
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.locator('#nav-services a').first().hover();
await page.waitForTimeout(300);
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.waitForTimeout(300);
await page.screenshot({ path: 'research/navbar-fixes/desktop-dropdown.jpg' });
await page.keyboard.press('Escape');
await expect(services).toBeFocused();
await page.keyboard.press('ArrowDown');
await expect(page.locator('#nav-services a').first()).toBeFocused();
await page.keyboard.press('Escape');
await expect(services).toHaveAttribute('aria-expanded', 'false');
await services.focus(); await page.keyboard.press('Enter');
await page.locator('#nav-services a').first().click();
await expect(page).toHaveURL(/our-services\/$/);
await expect(services).toHaveAttribute('aria-expanded', 'false');
await expect(page.locator('.nav-drop[data-active=true] > button')).toHaveText('Services');
await page.goto(base + '/shop/');
await expect(page.locator('.nav-drop[data-active=true] > button')).toHaveText('Shop');
for (const width of [360, 390, 700, 701, 768, 1000, 1100, 1101, 1200, 1440]) {
  await page.setViewportSize({ width, height: 844 });
  await page.goto(base + '/portfolio/');
  const boxes = await page.locator('.header').evaluate(n => [...n.children].filter(el => getComputedStyle(el).display !== 'none').map(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right }; }));
  for (let i = 1; i < boxes.length; i++) assert(boxes[i - 1].right <= boxes[i].left + 1, 'Navbar collision ' + width);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Overflow ' + width);
  await expect(page.getByRole('button', { name: 'Search products', exact: true })).toBeVisible();
  if (width <= 1100) {
    await page.getByRole('button', { name: 'Open menu' }).click();
    await expect(page.getByRole('dialog').getByRole('link', { name: 'Inspiration', exact: true })).toHaveAttribute('aria-current', 'page');
    await page.getByRole('dialog').getByRole('link', { name: 'Inspiration', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Open menu' })).toBeFocused();
  }
}
await page.setViewportSize({ width: 390, height: 700 });
await page.getByRole('button', { name: 'Open menu' }).click();
await page.getByRole('dialog').getByRole('link', { name: 'Book free consultation', exact: true }).click();
await expect(page).toHaveURL(/consultation\/$/);
await expect(page.getByRole('dialog')).toHaveCount(0);
await page.getByRole('button', { name: 'Search products', exact: true }).click();
await page.getByRole('textbox', { name: 'Search the collection' }).fill('sheer');
await page.getByRole('dialog').getByRole('button', { name: 'Search', exact: true }).click();
await expect(page).toHaveURL(/shop\/\?q=sheer/);
await expect(page.getByRole('dialog')).toHaveCount(0);
await page.getByRole('button', { name: 'Open menu' }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'research/navbar-fixes/mobile-menu.jpg' });
await page.setViewportSize({ width: 1440, height: 900 });
await expect(page.getByRole('dialog')).toHaveCount(0);
assert.equal(await page.evaluate(() => document.body.style.overflow), '');
await page.setViewportSize({ width: 1101, height: 430 });
await services.hover();
const panel = await page.locator('#nav-services').boundingBox();
assert(panel.y + panel.height <= 430, 'Dropdown clips on short screen');
await page.waitForTimeout(300);
await page.screenshot({ path: 'research/navbar-fixes/short-desktop.jpg' });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto(base + '/portfolio/');
await services.focus(); await page.keyboard.press('Enter');
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.keyboard.press('Escape');
await expect(services).toBeFocused();
assert.deepEqual(errors, []);
writeFileSync('research/navbar-fixes/results.json', JSON.stringify({ passed: true, errors, checks: ['Hover then click', 'Outside dismissal', 'Only one dropdown', 'Pointer gap bridge', 'Keyboard arrows and Escape', 'Route close and active section', 'Ten responsive widths', 'Same-page mobile navigation closes', 'Mobile search', 'Consultation link', 'Resize releases modal scroll lock', 'Short viewport dropdown', 'Reduced motion'] }, null, 2));
console.log('PASS: all navbar regression checks.');
await browser.close();

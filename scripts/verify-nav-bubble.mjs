import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1215, height: 884 } });
await page.addInitScript(() => sessionStorage.setItem('ch-intro', 'premium-v3'));
const errors = [];
page.on('pageerror', error => errors.push(error.message));
mkdirSync('research/nav-bubble', { recursive: true });
await page.goto('http://127.0.0.1:5173/portfolio/');
await page.evaluate(() => document.fonts.ready);
const bubble = page.locator('.nav-selection-bubble');
const current = async () => bubble.evaluate(n => {
  const values = getComputedStyle(n).clipPath.match(/-?[\d.]+/g).map(Number);
  return { left: values[3], right: values[1], running: n.getAnimations().filter(a => a.playState === 'running').length };
});
const assertAligned = async key => {
  await page.waitForTimeout(650);
  const { left, right } = await current();
  const target = await page.locator(`.desktop-nav > [data-nav-key="${key}"], .desktop-nav > .nav-drop > [data-nav-key="${key}"]`).evaluate(n => {
    const nav = n.closest('.desktop-nav').getBoundingClientRect(), rect = n.getBoundingClientRect();
    return { left: rect.left - nav.left, right: nav.right - rect.right };
  });
  assert(Math.abs(left - target.left) < 1, 'Bubble left edge at ' + key);
  assert(Math.abs(right - target.right) < 1, 'Bubble right edge at ' + key);
};
await assertAligned('Inspiration');
const before = await current();
await page.locator('.desktop-nav > a[data-nav-key="Contact"]').click();
await expect(page).toHaveURL(/contact-us\/$/);
await expect.poll(async () => (await current()).running).toBeGreaterThan(0);
const during = await current();
await page.locator('.header').screenshot({ path: 'research/nav-bubble/travelling.jpg', animations: 'allow' });
await assertAligned('Contact');
assert((await current()).left > before.left, 'Selection travelled towards Contact');
await page.locator('.header').screenshot({ path: 'research/nav-bubble/selected-contact.jpg' });
await page.goBack(); await assertAligned('Inspiration');
await page.locator('.desktop-nav > a[data-nav-key="About"]').click();
await page.locator('.desktop-nav > a[data-nav-key="Contact"]').click();
await assertAligned('Contact');
const services = page.locator('.desktop-nav').getByRole('button', { name: 'Services', exact: true });
await services.hover(); await assertAligned('Services');
await page.locator('#nav-services a').first().hover();
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.keyboard.press('Escape');
await assertAligned('Contact');
assert.equal(await bubble.getAttribute('aria-hidden'), 'true');
assert.equal(await bubble.evaluate(n => getComputedStyle(n).pointerEvents), 'none');
assert(await bubble.locator('.nav-bubble-label').evaluateAll(nodes => nodes.every(n => getComputedStyle(n).color === 'rgb(255, 255, 255)')));
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.locator('.desktop-nav > a[data-nav-key="Inspiration"]').click();
assert.equal((await current()).running, 0);
await assertAligned('Inspiration');
await page.setViewportSize({ width: 390, height: 844 });
await expect(page.locator('.desktop-nav')).not.toBeVisible();
await page.getByRole('button', { name: 'Open menu' }).click();
await page.getByRole('dialog').getByRole('link', { name: 'Contact', exact: true }).click();
await expect(page).toHaveURL(/contact-us\/$/);
await page.setViewportSize({ width: 1440, height: 900 });
await assertAligned('Contact');
assert.deepEqual(errors, []);
writeFileSync('research/nav-bubble/results.json', JSON.stringify({ passed: true, errors, during, checks: ['Visible travel between route links', 'Bubble fits target width', 'Browser Back', 'Rapid selection interruption', 'Dropdown preview and return', 'White lettering clipped to bubble', 'No pointer interception or duplicate accessible links', 'Reduced motion', 'Mobile menu and desktop resize'] }, null, 2));
console.log('PASS: sliding bubble, width fitting, rapid changes, dropdowns, Back, reduced motion and responsive navigation.');
await browser.close();

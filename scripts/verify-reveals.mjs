import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFileSync, mkdirSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
mkdirSync('research/motion-qa', { recursive: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.addInitScript(() => sessionStorage.setItem('ch-intro', 'wordmark-v4'));
await page.goto('http://127.0.0.1:5173/');
await page.addStyleTag({ content: 'html { scroll-behavior: auto !important; }' });
const picture = page.locator('.studio-visual');
await picture.scrollIntoViewIfNeeded();
await expect.poll(() => picture.evaluate(node => node.getAnimations().length)).toBeGreaterThan(0);
await page.waitForTimeout(1500);
assert.equal(await picture.evaluate(node => node.getAnimations().length), 0);
await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
await picture.scrollIntoViewIfNeeded();
await page.waitForTimeout(150);
assert.equal(await picture.evaluate(node => node.getAnimations().length), 0);
const card = page.locator('.home-products .product-card').first();
await card.scrollIntoViewIfNeeded();
await expect.poll(() => card.evaluate(node => node.getAnimations().length)).toBeGreaterThan(0);
await page.emulateMedia({ reducedMotion: 'reduce' });
await expect.poll(() => card.evaluate(node => node.getAnimations().length)).toBe(0);
assert.equal(await card.evaluate(node => getComputedStyle(node).opacity), '1');
writeFileSync('research/motion-qa/reveal-results.json', JSON.stringify({ passed: true, checks: ['Reveal starts when the section enters view', 'Completed reveal releases its animated styles', 'Returning to the section does not replay it', 'Reduced-motion preference change cancels an active reveal and leaves content visible'] }, null, 2));
console.log('PASS: live reveal, released styles, no replay, preference-change cancellation.');
await browser.close();

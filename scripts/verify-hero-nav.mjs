import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage();
await page.addInitScript(() => sessionStorage.setItem('ch-intro', 'premium-v3'));
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const out = 'research/hero-nav-qa';
mkdirSync(out, { recursive: true });
for (const width of [360, 390, 700, 768, 1024, 1100, 1200, 1440, 1920]) {
  await page.setViewportSize({ width, height: 1000 });
  await page.goto('http://127.0.0.1:5173/');
  await page.evaluate(async () => { await document.fonts.ready; const images = [...document.querySelectorAll('.room-hero img')]; images.forEach(i => i.loading = 'eager'); await Promise.all(images.map(i => i.decode().catch(() => {}))); });
  await page.waitForTimeout(1300);
  const boxes = await page.locator('.header').evaluate(n => [...n.children].filter(el => getComputedStyle(el).display !== 'none').map(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right }; }));
  for (let i = 1; i < boxes.length; i++) assert(boxes[i - 1].right <= boxes[i].left + 1, 'Navbar collision ' + width);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Overflow ' + width);
  const cta = await page.locator('.room-hero-copy .button').boundingBox();
  assert(cta.y + cta.height < 844, 'Hero action below fold ' + width);
  const lines = await page.locator('h1').evaluate(n => n.getBoundingClientRect().height / parseFloat(getComputedStyle(n).lineHeight));
  assert(lines < 2.15, 'Long hero heading ' + width);
  await page.screenshot({ path: `${out}/fold-${width}.jpg` });
  if ([390, 768, 1440].includes(width)) await page.locator('.room-hero').screenshot({ path: `${out}/hero-${width}.jpg` });
  console.log('PASS layout ' + width);
}
await page.setViewportSize({ width: 1440, height: 900 });
await page.goto('http://127.0.0.1:5173/');
const services = page.getByRole('button', { name: 'Services', exact: true });
await services.focus(); await page.keyboard.press('Enter');
await expect(services).toHaveAttribute('aria-expanded', 'true');
await page.getByRole('link', { name: 'All services', exact: true }).click();
await expect(page).toHaveURL(/our-services\/$/);
await page.getByRole('button', { name: 'Search products', exact: true }).click();
await page.getByRole('textbox', { name: 'Search the collection' }).fill('sheer');
await page.getByRole('dialog').getByRole('button', { name: 'Search', exact: true }).click();
await expect(page).toHaveURL(/shop\/\?q=sheer/);
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: 'Open menu', exact: true }).click();
await page.getByRole('dialog').getByRole('link', { name: 'Contact', exact: true }).click();
await expect(page).toHaveURL(/contact-us\/$/);
await expect(page.getByRole('dialog')).toHaveCount(0);
assert.deepEqual(errors, []);
writeFileSync(`${out}/results.json`, JSON.stringify({ passed: true, widths: [360,390,700,768,1024,1100,1200,1440,1920], errors, checks: ['Navbar collision bounds', 'Hero CTA above fold', 'Two-line heading', 'No overflow', 'Dropdown navigation', 'Product search', 'Mobile menu route change'] }, null, 2));
await browser.close();
